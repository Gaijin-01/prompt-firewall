"""Localized operator-facing strings for the approval card.

One semantic key set, three renderings. The key set is the contract; the
values are plain operator-facing text. Technical identifiers (commands,
paths, /dev/tcp, eval, firewall) are never translated.

The catalog is presentation-only: it never influences the firewall verdict.
"""

from __future__ import annotations

import threading
from contextvars import ContextVar
from typing import Any, Dict, Optional

__all__ = ["DEFAULT_LANGUAGE", "SUPPORTED_LANGUAGES", "current_language", "set_language", "t"]

#: Languages the card can render. Anything else falls back to English.
SUPPORTED_LANGUAGES = ("en", "ru", "zh-Hans")

#: Fallback when the active language has no catalog entry.
DEFAULT_LANGUAGE = "en"

_LANGUAGE: ContextVar[str] = ContextVar("pf_card_language", default=DEFAULT_LANGUAGE)
_LOCK = threading.Lock()


def current_language() -> str:
    """The language the card is currently rendered in."""
    return _LANGUAGE.get()


def set_language(lang: Optional[str]) -> str:
    """Set the rendering language; returns the language actually used."""
    target = str(lang or "").strip()
    if target not in SUPPORTED_LANGUAGES:
        target = DEFAULT_LANGUAGE
    _LANGUAGE.set(target)
    return target


def t(key: str, lang: Optional[str] = None, **params: Any) -> str:
    """Translate *key*; unknown key or language falls back to English."""
    catalog = _CATALOG.get(lang or current_language()) or _CATALOG[DEFAULT_LANGUAGE]
    value = catalog.get(key)
    if value is None:
        value = _CATALOG[DEFAULT_LANGUAGE].get(key)
    if value is None:
        return key
    if params:
        try:
            value = value.format(**params)
        except (KeyError, IndexError, ValueError):
            pass
    return value


